import fs from "node:fs";
import path from "node:path";

/**
 * Emit a Netlify scheduled function for the deterministic follow-up worker.
 * Netlify scans `.netlify/functions-internal`; the app's Nitro build writes its
 * own functions there, so this additive file survives the build and is uploaded
 * by `netlify deploy --functions=.netlify/functions-internal`.
 *
 * Netlify is the only host this project targets. Without Netlify (or without
 * DISCORD_FOLLOWUPS_SECRET) the app still works; only automatic sending is off.
 */
const root = process.cwd();
const functionsDir = path.join(root, ".netlify", "functions-internal");
if (!fs.existsSync(functionsDir)) {
  console.log(
    "[discord-followups] No .netlify/functions-internal; skipped scheduled function (not a Netlify build).",
  );
  process.exit(0);
}

const functionName = "feature-coordinator-discord-followups";
const source = `// Generated by scripts/emit-followup-scheduled-function.mjs.
export default async function handler(request) {
  const secret = process.env.DISCORD_FOLLOWUPS_SECRET; // guard:allow-env-credential — deployment-level shared worker secret, not a user credential
  if (!secret) {
    throw new Error(
      "DISCORD_FOLLOWUPS_SECRET is required for the Discord follow-up worker.",
    );
  }
  const base =
    process.env.URL || // guard:allow-env-credential — platform-provided site URL, not a user credential
    process.env.DEPLOY_PRIME_URL || // guard:allow-env-credential — platform-provided deploy URL, not a user credential
    process.env.APP_URL ||
    new URL(request.url).origin;
  const response = await fetch(new URL("/api/discord-followups/run", base), {
    method: "POST",
    headers: {
      Authorization: \`Bearer \${secret}\`,
      "content-type": "application/json",
      "user-agent": "feature-coordinator-discord-followups",
    },
    body: "{}",
  });
  const body = await response.text();
  if (!response.ok) {
    throw new Error(
      \`[discord-followups] worker failed (\${response.status}): \${body.slice(0, 500)}\`,
    );
  }
  console.log("[discord-followups] worker finished", body.slice(0, 500));
  return new Response(null, { status: 204 });
}

export const config = {
  name: "feature coordinator discord follow-ups",
  generator: "feature-coordinator build",
  schedule: "* * * * *",
  nodeBundler: "none",
};
`;

fs.writeFileSync(path.join(functionsDir, `${functionName}.mjs`), source);
console.log(
  `[discord-followups] Emitted Netlify scheduled function "${functionName}" (every minute).`,
);
